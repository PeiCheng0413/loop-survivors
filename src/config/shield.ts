/**
 * 幾何護盾（docs/DECISIONS.md §9b）。
 *
 * 護盾是**獨立於武器的插件**：不論裝備哪一把武器，護盾都存在，
 * 由它自己的那段積木腳本決定形狀。所以它的參數自成一區，
 * 不與武器數值混在一起。
 */

/**
 * 幾何護盾（§9b）。學生畫出的封閉多邊形就是防禦邊界。
 *
 * 形狀是靜態的 —— 只在腳本改動時算一次頂點，不需要每幀運算。
 */
export const SHIELD = {
  /** 邊的厚度，也是碰撞判定的容差 */
  thickness: 7,
  /** 每擋下一個敵人消耗的血量 */
  hitCost: 4,
  maxHp: 60,
  /** 破盾後的恢復時間（秒） */
  regenDelay: 6,
  /** 敵人被彈開的速度 */
  knockback: 260,
  /** 路徑腳本的容量，與攻擊腳本各自獨立（見 §9b） */
  capacity: 10,
  /**
   * 每一條邊提供的傷害加成。邊數越多的正多邊形越難算
   * （轉角 = 360 ÷ N），所以強度直接掛在邊數上。
   */
  buffPerSide: 0.04,
  /**
   * 判定閉合的容差（像素）。超過就沒有 buff。
   *
   * 缺口本身已經有代價（敵人穿得過來），但若照樣給滿 buff，
   * 等於告訴學生「算錯也沒差」—— 幾何練習的意義就沒了。
   * 給不給是二分的，因為配合「還差幾度」的提示，
   * 明確的過與不過比模糊的部分給分更好教。
   */
  closeTolerance: 8,
};
